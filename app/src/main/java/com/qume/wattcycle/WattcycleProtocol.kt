    fun modbusCrc16(data: ByteArray): Int {
        var crcHi = 0xFF
        var crcLo = 0xFF
        for (byte in data) {
            val idx = crcHi xor (byte.toInt() and 0xFF)
            crcHi = crcLo xor CRC_HI[idx]
            crcLo = CRC_LO[idx]
        }
        return (((crcLo and 0xFF) shl 8) or (crcHi and 0xFF)) and 0xFFFF
    }

    fun verifyCrc(data: ByteArray): Boolean {
        if (data.size < MIN_FRAME_SIZE) return false
        val payload = data.copyOfRange(0, data.size - 3)
        val expectedCrc = ((data[data.size - 3].toInt() and 0xFF) shl 8) or (data[data.size - 2].toInt() and 0xFF)
        return modbusCrc16(payload) == expectedCrc
    }

    fun buildReadFrame(address: Int, readCount: Int = 0, frameHead: Byte = FRAME_HEAD): ByteArray {
        val buf = ByteArray(11)
        buf[0] = frameHead
        buf[1] = 0x00 // version
        buf[2] = DEVICE_ADDR
        buf[3] = FUNC_READ
        buf[4] = ((address shr 8) and 0xFF).toByte()
        buf[5] = (address and 0xFF).toByte()
        buf[6] = ((readCount shr 8) and 0xFF).toByte()
        buf[7] = (readCount and 0xFF).toByte()
        val payload = buf.copyOfRange(0, 8)
        val crc = modbusCrc16(payload)
        buf[8] = ((crc shr 8) and 0xFF).toByte()
        buf[9] = (crc and 0xFF).toByte()
        buf[10] = FRAME_TAIL
        return buf
    }

    fun expectedResponseLength(firstPacket: ByteArray): Int? {
        if (firstPacket.size < 8) return null
        val dataLen = ((firstPacket[6].toInt() and 0xFF) shl 8) or (firstPacket[7].toInt() and 0xFF)
        return dataLen + 11
    }

    private fun parseCurrentNegative(data: ByteArray, offset: Int): Pair<Double, Int> {
        val b0 = data[offset]
        val b1 = data[offset + 1].toInt() and 0xFF
        val isNegative = (b0.toInt() and 0x80) != 0
        val hasDecimal = (b0.toInt() and 0x40) != 0
        val raw = b1 or ((b0.toInt() and 0x3F) shl 8)
        var current = if (hasDecimal) raw / 10.0 else raw.toDouble()
        if (isNegative) current = -current
        return Pair(current, offset + 2)
    }

    fun parseAnalogQuantity(data: ByteArray): ParsedAnalog? {
        try {
            var off = 0
            val cellCount = data[off].toInt() and 0xFF
            off += 1

            val cellVoltages = ArrayList<Double>(cellCount)
            for (i in 0 until cellCount) {
                val v = ((data[off].toInt() and 0xFF) shl 8) or (data[off + 1].toInt() and 0xFF)
                cellVoltages.add(v / 1000.0)
                off += 2
            }

            val tempCount = data[off].toInt() and 0xFF
            off += 1

            val mosRaw = ((data[off].toInt() and 0xFF) shl 8) or (data[off + 1].toInt() and 0xFF)
            val mosTemp = (mosRaw - 2730) / 10.0
            off += 2

            val pcbRaw = ((data[off].toInt() and 0xFF) shl 8) or (data[off + 1].toInt() and 0xFF)
            val pcbTemp = (pcbRaw - 2730) / 10.0
            off += 2

            val cellTemps = ArrayList<Double>()
            for (i in 0 until (tempCount - 2)) {
                val t = ((data[off].toInt() and 0xFF) shl 8) or (data[off + 1].toInt() and 0xFF)
                cellTemps.add((t - 2730) / 10.0)
                off += 2
            }

            val (current, newOff) = parseCurrentNegative(data, off)
            off = newOff

            val modVolRaw = ((data[off].toInt() and 0xFF) shl 8) or (data[off + 1].toInt() and 0xFF)
            val moduleVoltage = modVolRaw / 100.0
            off += 2

            val remCapRaw = ((data[off].toInt() and 0xFF) shl 8) or (data[off + 1].toInt() and 0xFF)
            val remainingCapacity = remCapRaw / 10.0
            off += 2

            val totCapRaw = ((data[off].toInt() and 0xFF) shl 8) or (data[off + 1].toInt() and 0xFF)
            val totalCapacity = totCapRaw / 10.0
            off += 2

            val cycleNumber = ((data[off].toInt() and 0xFF) shl 8) or (data[off + 1].toInt() and 0xFF)
            off += 2

            val desCapRaw = ((data[off].toInt() and 0xFF) shl 8) or (data[off + 1].toInt() and 0xFF)
            val designCapacity = desCapRaw / 10.0
            off += 2

            val soc = ((data[off].toInt() and 0xFF) shl 8) or (data[off + 1].toInt() and 0xFF)

            return ParsedAnalog(
                cellCount = cellCount,
                cellVoltages = cellVoltages,
                temperatureCount = tempCount,
                mosTemperature = mosTemp,
                pcbTemperature = pcbTemp,
                cellTemperatures = cellTemps,
                current = current,
                moduleVoltage = moduleVoltage,
                remainingCapacity = remainingCapacity,
                totalCapacity = totalCapacity,
                cycleNumber = cycleNumber,
                designCapacity = designCapacity,
                soc = soc
            )
        } catch (e: Exception) {
            return null
        }
    }

    fun parseProductInfo(data: ByteArray): ParsedProduct? {
        if (data.size != 60) return null
        return try {
            val fw = String(data, 0, 20, StandardCharsets.US_ASCII).trim { it <= ' ' || it == '\u0000' }
            val mfr = String(data, 20, 20, StandardCharsets.US_ASCII).trim { it <= ' ' || it == '\u0000' }
            val sn = String(data, 40, 20, StandardCharsets.US_ASCII).trim { it <= ' ' || it == '\u0000' }
            ParsedProduct(fw, mfr, sn)
        } catch (e: Exception) {
            null
        }
    }
